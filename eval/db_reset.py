"""Schema-per-case helpers for evaluation DB resets."""

from __future__ import annotations

import argparse
import asyncio
import logging
import uuid
from enum import Enum
from pathlib import Path
from typing import TYPE_CHECKING, Any

from psycopg import sql
from psycopg_pool import AsyncConnectionPool

from blue_horizon.load_data.rooms_pgsql import (
    DATA_PATH,
    ROOM_AVAIL_COLUMNS,
    ROOMS_COLUMNS,
    build_enum_definition,
    get_pgsql_conn_string,
    prepare_room_availability_dataframe,
    prepare_rooms_dataframe,
)

if TYPE_CHECKING:
    import pandas as pd

logger = logging.getLogger(__name__)


def _enum_to_scalar(value: Any) -> Any:  # noqa: ANN401
    """Return a scalar representation for Enum values.

    Args:
        value: Potential enum value that should be converted before insertion.

    Returns:
        The Enum member payload when ``value`` is an Enum, otherwise ``value``.

    """
    if isinstance(value, Enum):
        return value.value
    return value


def _normalize_enum_columns(
    df: pd.DataFrame,
    *,
    columns: tuple[str, ...],
) -> pd.DataFrame:
    """Normalize enumeration columns so they contain scalars.

    Args:
        df: DataFrame with Enum-typed columns generated by ``prepare_*`` helpers.
        columns: Tuple of column names that should be converted.

    Returns:
        Copy of ``df`` with the requested ``columns`` coerced to their literal values.

    """
    normalized = df.copy()
    for column in columns:
        normalized[column] = normalized[column].apply(_enum_to_scalar)
    return normalized


async def create_case_schema(   # noqa: PLR0915
    *,
    pool: AsyncConnectionPool[Any],
    schema: str,
    data_path: str | Path,
) -> None:
    """Create schema-local enums/tables and load baseline data.

    Args:
        pool: Async connection pool providing Postgres connections.
        schema: Name of the schema dedicated to the current evaluation case.
        data_path: Filesystem path containing the pickled datasets.

    Raises:
        Any exception raised while creating the schema is surfaced after a cleanup
        attempt that drops the schema when it was newly created.

    """
    path = Path(data_path)
    df_rooms, room_type_values, bed_type_values, room_status_values = (
        prepare_rooms_dataframe(
            path,
        )
    )
    df_avail, availability_status_values = prepare_room_availability_dataframe(path)

    room_type_def = build_enum_definition(room_type_values)
    room_bed_type_def = build_enum_definition(bed_type_values)
    room_status_def = build_enum_definition(room_status_values)
    availability_status_def = build_enum_definition(availability_status_values)

    normalized_rooms = _normalize_enum_columns(
        df_rooms,
        columns=("type", "bed_type", "status"),
    )
    normalized_avail = _normalize_enum_columns(
        df_avail,
        columns=("status",),
    )

    rooms_rows = normalized_rooms[ROOMS_COLUMNS].to_numpy().tolist()
    avail_rows = normalized_avail[ROOM_AVAIL_COLUMNS].to_numpy().tolist()

    schema_ident = sql.Identifier(schema)
    schema_created = False

    schema_check = sql.SQL(
        "SELECT 1 FROM information_schema.schemata WHERE schema_name = %s",
    )

    # Add as a comment and change each run to make sure we don't hit the cache,
    # Which causes a problem when re-uploading to a schema with the same name
    run_token = uuid.uuid4().hex

    rooms_insert_sql = (
        sql.SQL("/* reset-run: {} */ ").format(sql.Literal(run_token))
        + sql.SQL(
            "INSERT INTO rooms ("
            "room_id, room_number, floor, type, square_feet, "
            "basic_amenities, additional_amenities, max_occupancy, "
            "bed_type, view_type, accessibility, status, last_renovation, "
            "base_rate, max_rate"
            ") VALUES ("
            "%s, %s, %s, %s::room_type, %s, %s, %s, %s, %s::room_bed_type, "
            "%s, %s, %s::room_status_type, %s, %s, %s"
            ");",
        )
    )

    avail_insert_sql = (
        sql.SQL("/* reset-run: {} */ ").format(sql.Literal(run_token))
        + sql.SQL(
            "INSERT INTO room_availability ("
            "room_id, room_number, date, status, price, max_occupancy"
            ") VALUES ("
            "%s, %s, %s, %s::availability_status_type, %s, %s"
            ");",
        )
    )

    try:
        async with pool.connection() as conn, conn.transaction():
            async with conn.cursor() as cur:
                await cur.execute(schema_check, (schema,))
                exists = await cur.fetchone()
            if exists is None:
                schema_created = True

            await conn.execute(
                sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(schema_ident),
            )
            await conn.execute(
                sql.SQL("SET search_path TO {}").format(schema_ident),
            )

            await conn.execute("DROP TABLE IF EXISTS room_availability CASCADE;")
            await conn.execute("DROP TABLE IF EXISTS rooms CASCADE;")
            await conn.execute("DROP TYPE IF EXISTS availability_status_type CASCADE;")
            await conn.execute("DROP TYPE IF EXISTS room_type CASCADE;")
            await conn.execute("DROP TYPE IF EXISTS room_bed_type CASCADE;")
            await conn.execute("DROP TYPE IF EXISTS room_status_type CASCADE;")

            await conn.execute(
                sql.SQL("CREATE TYPE {} AS ENUM ").format(
                    sql.Identifier("room_type"),
                )
                + room_type_def,
            )
            await conn.execute(
                sql.SQL("CREATE TYPE {} AS ENUM ").format(
                    sql.Identifier("room_bed_type"),
                )
                + room_bed_type_def,
            )
            await conn.execute(
                sql.SQL("CREATE TYPE {} AS ENUM ").format(
                    sql.Identifier("room_status_type"),
                )
                + room_status_def,
            )
            await conn.execute(
                sql.SQL("CREATE TYPE {} AS ENUM ").format(
                    sql.Identifier("availability_status_type"),
                )
                + availability_status_def,
            )

            await conn.execute(
                """
                CREATE TABLE rooms (
                    room_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    room_number INT NOT NULL,
                    floor INT NOT NULL,
                    type room_type,
                    square_feet INT,
                    basic_amenities TEXT[],
                    additional_amenities TEXT[],
                    max_occupancy INT,
                    bed_type room_bed_type,
                    view_type TEXT[],
                    accessibility BOOLEAN,
                    status room_status_type,
                    last_renovation DATE,
                    base_rate NUMERIC(10, 2),
                    max_rate NUMERIC(10, 2)
                );
                """,
            )

            await conn.execute(
                """
                CREATE TABLE room_availability (
                    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    room_id INT NOT NULL,
                    room_number INT NOT NULL,
                    date DATE NOT NULL,
                    status availability_status_type,
                    price NUMERIC(8,2),
                    max_occupancy INT,
                    FOREIGN KEY (room_id) REFERENCES rooms(room_id),
                    CONSTRAINT room_availability_room_id_date_uniq UNIQUE (room_id, date)
                );
                """,  # noqa: E501
            )

            if rooms_rows:
                async with conn.cursor() as cur:
                    await cur.executemany(rooms_insert_sql, rooms_rows)
            if avail_rows:
                async with conn.cursor() as cur:
                    await cur.executemany(avail_insert_sql, avail_rows)

    except Exception:
        if schema_created:
            try:
                await drop_case_schema(pool=pool, schema=schema)
            except Exception:
                logger.exception("Failed to drop schema %s during cleanup", schema)
        raise


async def drop_case_schema(
    *,
    pool: AsyncConnectionPool[Any],
    schema: str,
) -> None:
    """Drop a schema reserved for an evaluation case.

    Args:
        pool: Async connection pool providing Postgres connections.
        schema: Schema name to drop (CASCADE).

    """
    schema_ident = sql.Identifier(schema)
    async with pool.connection() as conn:
        await conn.execute(
            sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(schema_ident),
        )


async def _main() -> None:
    """Parse CLI args and run the case schema bootstrap workflow.

    The CLI accepts ``--schema`` (required) and ``--data-path`` so data loading can
    be pointed at a custom pickle directory. A single connection pool is opened
    for the duration of the run.

    """
    parser = argparse.ArgumentParser(description="Create a case schema for evaluation.")
    parser.add_argument("--schema", required=True, help="Schema name to create.")
    parser.add_argument(
        "--data-path",
        type=Path,
        default=DATA_PATH,
        help="Path to the pickled room datasets.",
    )
    args = parser.parse_args()

    pool = AsyncConnectionPool(
        conninfo=get_pgsql_conn_string(),
        min_size=1,
        max_size=1,
        timeout=30,
        open=False,
    )

    await pool.open()
    try:
        await create_case_schema(
            pool=pool, schema=args.schema, data_path=args.data_path,
        )
    finally:
        await pool.close()


if __name__ == "__main__":
    asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    asyncio.run(_main())
