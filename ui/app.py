@st.fragment(run_every=_HEALTH_POLL_ONLINE_INTERVAL_S)
def _render_online_poll() -> None:
    """Silently poll the API and trigger a full app rerun if it goes offline.

    Registered only while the API is online. Streamlit removes the fragment
    from the render tree on the next full rerun (when the API is down), so
    polling stops automatically once the chatbot goes offline.
    """
    if not _check_health():
        st.rerun()


@st.fragment(run_every=_HEALTH_POLL_OFFLINE_INTERVAL_S)
def _render_recovery_poll() -> None:
    """Silently poll the API and trigger a full app rerun when it recovers.

    Registered only while the API is offline. Streamlit removes the fragment
    from the render tree on the next full rerun (when the API is back), so
    polling stops automatically once the chatbot comes online.
    """
    if _check_health():
        st.rerun()


def _render_login_page() -> None:
    """Render the sign-in page shown to unauthenticated visitors."""
    st.info("Please sign in with your Google account to access the concierge.")
    st.button(
        "Sign in with Google",
        on_click=st.login,
        use_container_width=True,
    )


def _render_guest_assignment() -> None:
    """Claim an exclusive guest for the session, or show why none is held.

    A session with no guest yet claims a random one nobody else currently
    holds, so concurrent visitors to the shared deployment never land on the
    same guest and collide over their reservations. A session that already
    holds a claim -- including one just restored from the URL after a hard
    refresh -- has its activity timestamp refreshed here, so an
    idle-but-connected tab does not lose its seat before
    `_GUEST_CLAIM_TTL_S` actually elapses. A claim restored from the URL
    that turns out to belong to someone else now (this session's earlier
    claim expired and was reassigned before it came back) falls through to
    claiming a fresh guest instead of stealing it back. If every seeded
    guest is claimed, this shows a capacity message instead and leaves
    `customer_id` unset, which the chat input is disabled on.
    """
    customer_id = st.session_state.customer_id
    if customer_id is not None:
        customer_id = _touch_claim(customer_id, st.session_state.session_id)
        st.session_state.customer_id = customer_id

    customers = _fetch_customers()
    if not customers:
        st.warning("Could not load the guest list.")
        return

    if customer_id is None:
        customer_id = _try_claim_guest(
            st.session_state.session_id,
            [c["customer_id"] for c in customers],
        )
        if customer_id is None:
            st.warning(
                "We're at capacity right now. Please check back in a few minutes.",
            )
            return
        st.session_state.customer_id = customer_id

    guest = next((c for c in customers if c["customer_id"] == customer_id), None)
    if guest is None:
        # The guest list changed under us (e.g. a demo database reset) --
        # release the now-stale claim and let the next rerun claim a fresh
        # guest instead of showing a ghost id.
        _release_claim(customer_id)
        st.session_state.customer_id = None
        return

    _persist_guest_identity(customer_id)
    st.caption(f"You're browsing as **{guest['first_name']} {guest['last_name']}**")


def _render_reservations() -> None:
    """Render the "Your reservations" sidebar panel for the current guest.

    Built strictly from `GET /v1/bookings`, never from chat text -- the same
    rule the confirmation dialog follows, and for the same reason: a receipt
    the guest cannot go back and check is barely a receipt. Cancelled
    bookings are left out; a guest can still ask the chat about those.
    """
    st.subheader("Your reservations")
    customer_id = st.session_state.customer_id
    if customer_id is None:
        return

    raw_bookings = _fetch_bookings(customer_id)
    if raw_bookings is None:
        st.caption("Could not load your reservations right now.")
        return

    bookings = [b for b in raw_bookings if b["status"] != "cancelled"]
    if not bookings:
        st.caption("No reservations yet.")
        return

    for booking in bookings:
        label = booking["confirmation_number"] or f"Booking {booking['booking_id']}"
        with st.container(border=True):
            st.markdown(f"**{label}** ({booking['status']})")
            for room in booking["rooms"]:
                st.caption(
                    f"Room {room['room_number']}: {room['check_in']} → "
                    f"{room['check_out']} — ${room['total_amount']}",
                )
            if booking["rooms"]:
                st.caption(f"Total: ${booking['total_amount']}")


def _handle_sign_out() -> None:
    """Release the session's guest claim, then sign the user out.

    A sign-out is a deliberate disconnect, so the claim is freed immediately
    rather than left to expire via `_GUEST_CLAIM_TTL_S`. Also drops the
    `sid`/`cid` query params, so signing back in claims a fresh guest
    instead of the URL silently reattaching the one just released.
    """
    _release_claim(st.session_state.customer_id)
    st.session_state.customer_id = None
    for param in ("sid", "cid"):
        if param in st.query_params:
            del st.query_params[param]
    st.logout()


def _render_sidebar() -> None:
    """Render the sidebar: auth info, guest assignment, health, and controls."""
    with st.sidebar:
        st.header("Blue Horizon")

        if _AUTH_ENABLED:
            st.caption(f"Signed in as **{st.user.name or st.user.email}**")
            st.button("Sign out", on_click=_handle_sign_out, use_container_width=True)
            st.divider()

        _render_guest_assignment()
        st.divider()

        # Published to session state so _render_pending_resend() (rendered
        # later, in _render_chat()) can gate "Send again" on it without a
        # second /v1/health round trip of its own.
        online = _check_health()
        st.session_state.api_online = online
        # This reports readiness (`/v1/health`: startup finished), not
        # whether the model provider, Redis, or Postgres are reachable right
        # now; a failure during a turn shows up in the chat's own failure
        # block instead. Hence "Running", which it can honestly claim.
        if online:
            st.success("Service: Running")
            _render_online_poll()
        else:
            st.error("Service: Unavailable")
            _render_recovery_poll()

        st.divider()

        if st.button("New Conversation", use_container_width=True):
            _reset_session()
            st.rerun()

        st.divider()
        _render_reservations()


def _md(text: str) -> None:
    """Render text as Markdown with dollar signs escaped to prevent LaTeX parsing.

    Args:
        text: Text to render as Markdown.

    """
    st.markdown(text.replace("$", r"\$"))


def _parse_sse_line(line: str) -> dict[str, Any] | None:
    """Parse one line of an SSE stream into its JSON event payload.

    Args:
        line: One line read from the response body.

    Returns:
        dict[str, Any] | None: The decoded event, or ``None`` for lines that
        are not a ``data: `` event or fail to decode (e.g. a keepalive
        comment line).

    """
    if not line.startswith("data: "):
        return None
    try:
        return json.loads(line[6:])
    except json.JSONDecodeError:
        return None


@dataclasses.dataclass(frozen=True, slots=True)
class ChatTurnResult:
    """Outcome of one `_stream_message` call.

    Attributes:
        ok: Whether the assistant actually produced a reply. False for
            every failure this module can classify -- an `error` SSE event,
            a non-2xx HTTP response, a timeout, or an unreachable API --
            since none of those means the turn is safe to treat as answered.
            These are Tier B failures in the failure-handling tiering: the
            system never auto-retries a chat turn server-side (it may
            already have mutated the proposal store or the conversation
            checkpoint, and it always consumes LLM tokens), but a
            guest-initiated resend of the exact same text is always safe,
            which is what `_render_pending_resend` offers when `ok` is
            False.
        text: The assistant's reply on success, or guest-facing failure copy
            on failure. Never raw exception text either way.
        proposal: A pending proposal dict, if the turn created one. Always
            `None` when `ok` is False.

    """

    ok: bool
    text: str
    proposal: dict[str, Any] | None


def _handle_stream_event(
    event: dict[str, Any],
    status: DeltaGenerator,
    pending_proposal: dict[str, Any] | None,
) -> tuple[dict[str, Any] | None, ChatTurnResult | None]:
    """Apply one SSE event to the status widget.

    Args:
        event: Decoded SSE event.
        status: The turn's `st.status` widget.
        pending_proposal: Proposal captured from an earlier event this turn,
            if any.

    Returns:
        tuple: `(pending_proposal, result)`. `pending_proposal` carries
        forward to the next event; `result` is non-``None`` exactly when the
        caller should return it immediately (an `error` or `done` event ends
        the turn).

    """
    event_type = event.get("type")
    if event_type == "stage":
        status.update(label=event["label"], state="running")
    elif event_type == "error":
        status.update(label="Error", state="error")
        message = str(event.get("message", "Something went wrong."))
        return pending_proposal, ChatTurnResult(ok=False, text=message, proposal=None)
    elif event_type == "done":
        status.update(label="Done", state="complete")
        response_text = str(event.get("response", "No response received."))
        return pending_proposal, ChatTurnResult(
            ok=True, text=response_text, proposal=pending_proposal,
        )
    elif event_type == "proposal":
        # `.get()`, not indexing: a malformed event must not crash the turn
        # with a bare KeyError that the generic exception handler below
        # would otherwise report as an unhelpful "Could not reach the API".
        proposal_id = event.get("proposal_id")
        action = event.get("action")
        summary = event.get("summary")
        if proposal_id is None or action is None or summary is None:
            logger.warning("Malformed proposal event, ignoring: %r", event)
        else:
            pending_proposal = {
                "proposal_id": proposal_id,
                "action": action,
                "summary": summary,
            }
    return pending_proposal, None


def _stream_message(thread_id: str, customer_id: int, text: str) -> ChatTurnResult:
    """Stream a chat turn from the unified endpoint and display live progress.

    Connects to ``POST /v1/chat`` with ``Accept: text/event-stream`` and
    updates a :func:`streamlit.status` widget as each event arrives.

    This function must be called inside a ``st.chat_message`` context so that
    the status widget is rendered inside the assistant bubble.

    Args:
        thread_id: Unique identifier for the current conversation thread.
        customer_id: The current guest, bound to `thread_id` on first use.
        text: The user's message text.

    Returns:
        ChatTurnResult: The assistant's reply, or a failure the guest can
        retry with "Send again".

    """
    status = st.status("Routing your request…", state="running")
    pending_proposal: dict[str, Any] | None = None
    try:
        with httpx2.stream(
            "POST",
            f"{_API_BASE}/v1/chat",
            json={"thread_id": thread_id, "customer_id": customer_id, "text": text},
            headers={"Accept": "text/event-stream"},
            timeout=_CHAT_TIMEOUT_S,
        ) as response:
            response.raise_for_status()
            for line in response.iter_lines():
                event = _parse_sse_line(line)
                if event is None:
                    continue
                pending_proposal, result = _handle_stream_event(
                    event, status, pending_proposal,
                )
                if result is not None:
                    return result
    except httpx2.HTTPStatusError as exc:
        _log_api_failure(exc, "Chat request for thread_id=%s failed.", thread_id)
        error_message = _http_error_message(exc)
    # None of the failure copy below tells the guest to try again: it is
    # rendered above the "Send again" button, which is that instruction.
    except httpx2.TimeoutException as exc:
        # Logged here only: the API may still be running the turn.
        _log_api_failure(exc, "Chat request for thread_id=%s timed out.", thread_id)
        error_message = "The concierge took too long to reply."
    except Exception as exc:  # noqa: BLE001
        _log_api_failure(exc, "Chat request for thread_id=%s failed.", thread_id)
        error_message = "Could not reach the concierge."
    else:
        return ChatTurnResult(
            ok=True, text="No response received.", proposal=pending_proposal,
        )

    status.update(label="Error", state="error")
    return ChatTurnResult(ok=False, text=error_message, proposal=None)


def _http_error_message(exc: httpx2.HTTPStatusError) -> str:
    """Translate a chat-endpoint HTTP error into user-facing copy.

    Args:
        exc: HTTP status error raised by the chat request.

    Returns:
        str: User-facing error message.

    """
    if exc.response.status_code == _HTTP_SERVICE_UNAVAILABLE:
        # The readiness gate's own body carries `message`, already picked
        # between "still starting up" and "won't resolve on its own" server
        # side -- see api.app._not_ready_response. The fallback only fires
        # if that body could not be parsed at all.
        message = _response_field(exc.response, "message")
        return message or "The concierge is still starting up."
    return (
        f"Something went wrong on our side (error {exc.response.status_code})."
    )


def _render_book_summary(summary: dict[str, Any]) -> None:
    """Render a `book` proposal's line items inside the confirmation dialog.

    Args:
        summary: Proposal summary with a `rooms` list and a `total`.

    """
    for room in summary["rooms"]:
        st.write(
            f"Room {room['room_number']}: {room['check_in']} → {room['check_out']} "
            f"({room['nights']} nights) — ${room['amount']}",
        )
    st.markdown(f"**Total: ${summary['total']}**")


def _render_cancel_summary(summary: dict[str, Any]) -> None:
    """Render a `cancel` proposal's line items inside the confirmation dialog.

    Args:
        summary: Proposal summary with a `rooms` list and a refund `total`.

    """
    for room in summary["rooms"]:
        st.write(f"Room {room['room_number']}: refund ${room['amount']}")
    st.markdown(f"**Total refund: ${summary['total']}**")


def _render_modify_summary(summary: dict[str, Any]) -> None:
    """Render a `modify` proposal's before/after changes inside the dialog.

    Args:
        summary: Proposal summary with a `changes` list and a new `total`.

    """
    for change in summary["changes"]:
        before, after = change["before"], change["after"]
        st.write(
            f"Room {before['room_number']} ({before['check_in']} → "
            f"{before['check_out']}) **becomes** Room {after['room_number']} "
            f"({after['check_in']} → {after['check_out']})",
        )
    st.markdown(f"**New total: ${summary['total']}**")


_SUMMARY_RENDERERS = {
    "book": _render_book_summary,
    "cancel": _render_cancel_summary,
    "modify": _render_modify_summary,
}

# Shown instead of a "refused" outcome's own detail when this confirm
# attempt followed one that came back "unavailable" or "unreachable" on the
# same proposal. In that situation the earlier write may have already
# landed with its acknowledgement lost, so asserting the nights were taken
# by someone else would tell the guest the opposite of the truth.
_AMBIGUOUS_REFUSAL_MSG = (
    "We could not confirm whether this went through. Please check "
    '"Your reservations" before trying again.'
)


@st.dialog("Review your request", dismissible=False)
def _render_proposal_dialog(proposal: dict[str, Any]) -> None:
    """Render the confirmation dialog for a pending proposal.

    Built strictly from `proposal["summary"]` -- resolved, priced line items
    computed by the application -- and never from assistant chat text. This
    is the load-bearing detail from the design this UI implements: the
    dialog and the eventual commit must never be able to disagree, so do not
    "simplify" this to reuse the assistant's message text instead.

    Not dismissible, so Confirm and Cancel are the only ways out. A click
    outside the dialog, ESC, or its X would close it in the browser only:
    `pending_proposal` stays set and the proposal stays pending on the
    server, so the dialog would reappear on the guest's next unrelated
    interaction, such as switching guests in the sidebar.

    A confirm that comes back `unavailable` or `unreachable` (see
    `ConfirmOutcome`) leaves the dialog open with Confirm still enabled
    instead of closing it: the write was never evaluated, so pressing
    Confirm again is a clean retry, not a duplicate booking attempt.

    Args:
        proposal: Pending proposal dict with `proposal_id`, `action`,
            `summary`, and (once a retry-safe failure has occurred)
            `had_operational_failure`.

    """
    renderer = _SUMMARY_RENDERERS[proposal["action"]]
    renderer(proposal["summary"])

    col_confirm, col_cancel = st.columns(2)
    if col_confirm.button("Confirm", type="primary", use_container_width=True):
        customer_id = st.session_state.customer_id
        # Set by an earlier attempt on this same proposal that came back
        # "unavailable" or "unreachable" -- see the branch below. Tracked so
        # a "refused" outcome on *this* attempt can be recognised as the
        # lost-acknowledgement case: the earlier write may have actually
        # landed, so this retry's refusal does not necessarily mean the
        # nights were taken by someone else. Step 18 (reconciliation) is the
        # real fix; this is the interim mitigation described in the plan.
        had_operational_failure = proposal.get("had_operational_failure", False)
        outcome = _confirm_proposal(proposal["proposal_id"], customer_id)

        if outcome.keep_pending:
            proposal["had_operational_failure"] = True
            st.session_state.pending_proposal = proposal
            st.warning(outcome.message)
        else:
            message = _AMBIGUOUS_REFUSAL_MSG if (
                outcome.status == "refused" and had_operational_failure
            ) else outcome.message
            st.session_state.pending_proposal = None
            st.session_state.messages.append({"role": "assistant", "content": message})
            st.rerun()

    if col_cancel.button("Cancel", use_container_width=True):
        customer_id = st.session_state.customer_id
        _dismiss_proposal(proposal["proposal_id"], customer_id)
        st.session_state.pending_proposal = None
        st.rerun()


def _submit_chat_message(prompt: str) -> None:
    """Send one chat turn and fold the outcome into session state.

    On success, appends the assistant's reply to history and stores any
    pending proposal. On failure, the guest's own message (already in
    history by the time this is called) is left standing alone -- nothing
    is fabricated to look like an assistant reply -- and the text plus
    failure copy are stashed for `_render_pending_resend` instead.

    Must be called inside a ``st.chat_message("assistant")`` context so a
    successful reply renders inside the assistant bubble.

    Args:
        prompt: The guest's message text for this turn.

    """
    result = _stream_message(
        st.session_state.thread_id, st.session_state.customer_id, prompt,
    )
    if result.ok:
        _md(result.text)
        st.session_state.messages.append(
            {"role": "assistant", "content": result.text},
        )
        st.session_state.pending_proposal = result.proposal
        st.session_state.pending_resend = None
        st.session_state.pending_resend_message = None
    else:
        st.session_state.pending_resend = prompt
        st.session_state.pending_resend_message = result.text


def _render_pending_resend() -> None:
    """Render the system-state block for a chat turn that failed to complete.

    Shown as its own block rather than an assistant bubble, since nothing
    was actually said -- the guest's own message stays in history as-is,
    and this is what offers the resend instead of a bare "try again"
    sentence. "Send again" replays the exact same text and stays disabled
    until `_render_sidebar` observes the API healthy again, wiring the
    already-existing recovery poll to this control for the first time.
    """
    prompt = st.session_state.pending_resend
    if prompt is None:
        return
    st.warning(st.session_state.pending_resend_message)
    online = st.session_state.api_online
    if st.button("Send again", disabled=not online, use_container_width=True):
        with st.chat_message("assistant"):
            _submit_chat_message(prompt)
        st.rerun()
    if not online:
        st.caption("Send again will be available once the service is back.")


def _render_chat() -> None:
    """Render the chat message history, pending proposal, and new user input."""
    for msg in st.session_state.messages:
        with st.chat_message(msg["role"]):
            _md(msg["content"])

    _render_pending_resend()

    if st.session_state.pending_proposal is not None:
        _render_proposal_dialog(st.session_state.pending_proposal)

    placeholder = "Ask about the hotel, or get help searching or booking rooms..."
    if prompt := st.chat_input(
        placeholder, disabled=st.session_state.customer_id is None,
    ):
        _dismiss_pending_proposal()
        # A new message supersedes any resend still offered for an earlier,
        # failed one -- typing past it means the guest has moved on.
        st.session_state.pending_resend = None
        st.session_state.pending_resend_message = None

        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            _md(prompt)

        with st.chat_message("assistant"):
            _submit_chat_message(prompt)
        st.rerun()


