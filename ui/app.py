def _check_health() -> bool:
    """Poll the API health endpoint.

    Returns:
        ``True`` if the API responds with HTTP 200, ``False`` otherwise
        (including network errors and HTTP 503 while the agent is starting up).

    """
    try:
        response = httpx2.get(f"{_API_BASE}/v1/health", timeout=_HEALTH_TIMEOUT_S)
        return response.status_code == _HTTP_OK  # noqa: TRY300
    except Exception:  # noqa: BLE001
        return False


@st.cache_data(ttl=300, show_spinner=False)
def _fetch_customers_uncached() -> list[dict[str, Any]]:
    """Fetch the guest list backing automated guest assignment.

    Cached for five minutes: the seeded customer list never changes between
    a demo database reload. Streamlit only caches on a successful return, so
    a failed lookup (e.g. a cold booking-DB connection) is retried on the
    next call instead of being memoized as "no guests."

    Returns:
        list[dict[str, Any]]: `{customer_id, first_name, last_name}` per
        guest.

    Raises:
        httpx2.HTTPError: If the API could not be reached or returned an
            error status.

    """
    response = httpx2.get(f"{_API_BASE}/v1/customers", timeout=_DATA_TIMEOUT_S)
    response.raise_for_status()
    return response.json()


def _fetch_customers() -> list[dict[str, Any]]:
    """Fetch the guest list, logging and falling back to empty on failure.

    Returns:
        list[dict[str, Any]]: `{customer_id, first_name, last_name}` per
        guest, or an empty list if the API could not be reached.

    """
    try:
        return _fetch_customers_uncached()
    except Exception as exc:  # noqa: BLE001
        _log_api_failure(exc, "Could not fetch the guest list.")
        return []


def _fetch_bookings(customer_id: int) -> list[dict[str, Any]] | None:
    """Fetch one guest's bookings for the reservations panel.

    Args:
        customer_id: Guest whose bookings to fetch.

    Returns:
        list[dict[str, Any]] | None: Booking summaries, or ``None`` if the
        API could not be reached. Deliberately distinct from an empty list,
        which means the guest genuinely has no reservations -- collapsing
        the two would render a backend outage as "No reservations yet.".

    """
    try:
        response = httpx2.get(
            f"{_API_BASE}/v1/bookings",
            params={"customer_id": customer_id},
            timeout=_DATA_TIMEOUT_S,
        )
        response.raise_for_status()
        return response.json().get("bookings", [])
    except Exception as exc:  # noqa: BLE001
        _log_api_failure(
            exc, "Could not fetch bookings for customer_id=%s.", customer_id,
        )
        return None


def _log_api_failure(exc: BaseException, message: str, *args: object) -> None:
    """Log a failed API call, without a traceback when it is expected.

    A refused connection, a timeout, or an error status means the API is down
    or unhealthy, which the sidebar already reports, and its traceback runs
    to dozens of lines that say nothing ``exc`` itself does not. Those are
    logged as one warning line. Anything else, such as a malformed response
    body, is a defect and keeps its traceback.

    Args:
        exc: The exception the call raised.
        message: Log message format string.
        *args: Arguments for ``message``.

    """
    if isinstance(exc, httpx2.HTTPError):
        logger.warning(f"{message} %r", *args, exc)  # noqa: G004
        return
    logger.warning(message, *args, exc_info=exc)


@dataclasses.dataclass(frozen=True, slots=True)
class ConfirmOutcome:
    """Structured result of a `_confirm_proposal` call.

    Attributes:
        status: One of ``confirmed``, ``refused``, ``expired``,
            ``wrong_guest``, ``unavailable``, or ``unreachable``.
        message: Guest-facing text for this outcome, taken from the
            response body's ``detail``/``message`` where the server
            supplied one.
        keep_pending: Whether the confirmation dialog should stay open with
            Confirm still enabled. True only for ``unavailable`` and
            ``unreachable`` -- the two cases where the write was never
            evaluated (see `blue_horizon.agents.booking.proposals
            .ProposalStore.confirm`), so trying again is safe. Every other
            status is terminal.

    """

    status: str
    message: str
    keep_pending: bool


# Maps a non-2xx `/v1/booking/confirm` status code to its ConfirmOutcome
# status. Anything else (an unexpected 500, say) falls back to
# "unreachable" in `_confirm_proposal`: the safest assumption when the
# outcome is genuinely unknown is that it is still safe to try again,
# never that the guest already has the room.
_CONFIRM_STATUS_BY_HTTP_CODE: dict[int, str] = {
    _HTTP_NOT_FOUND: "expired",
    _HTTP_FORBIDDEN: "wrong_guest",
    _HTTP_CONFLICT: "refused",
    _HTTP_SERVICE_UNAVAILABLE: "unavailable",
}


def _response_field(response: httpx2.Response, field: str) -> str | None:
    """Best-effort extraction of one string field from a JSON response body.

    Args:
        response: An HTTP response that may or may not carry a JSON object
            body.
        field: The key to read (e.g. ``"detail"`` for a FastAPI
            ``HTTPException``, ``"message"`` for the ``/v1/chat`` readiness
            gate's own body shape).

    Returns:
        str | None: The field's string value, or ``None`` if the body was
        not JSON, was not an object, or the field was missing or not a
        string.

    """
    try:
        body = response.json()
    except ValueError:
        return None
    value = body.get(field) if isinstance(body, dict) else None
    return value if isinstance(value, str) else None


def _response_detail(response: httpx2.Response) -> str | None:
    """Best-effort extraction of a JSON error body's ``detail`` field.

    Args:
        response: An HTTP response that may or may not carry a JSON body
            shaped like FastAPI's ``HTTPException`` (``{"detail": "..."}"``).

    Returns:
        str | None: The `detail` string, or ``None`` if the body was not
        JSON, was not an object, or had no `detail` key.

    """
    return _response_field(response, "detail")


def _confirm_proposal(proposal_id: str, customer_id: int) -> ConfirmOutcome:
    """Confirm a pending proposal.

    Args:
        proposal_id: Proposal to confirm.
        customer_id: Guest confirming it.

    Returns:
        ConfirmOutcome: What happened, and whether the confirmation dialog
        should stay open for a retry.

    """
    try:
        response = httpx2.post(
            f"{_API_BASE}/v1/booking/confirm",
            json={"proposal_id": proposal_id, "customer_id": customer_id},
            timeout=_CHAT_TIMEOUT_S,
        )
    except Exception as exc:  # noqa: BLE001
        _log_api_failure(
            exc, "Could not reach the API to confirm proposal_id=%s.", proposal_id,
        )
        return ConfirmOutcome(
            status="unreachable",
            message=(
                "Could not reach the booking system. Your request is still "
                "pending — try Confirm again."
            ),
            keep_pending=True,
        )

    if response.status_code == _HTTP_OK:
        return ConfirmOutcome(
            status="confirmed", message=response.json()["message"], keep_pending=False,
        )

    if response.status_code not in _CONFIRM_STATUS_BY_HTTP_CODE:
        # The mapped statuses are logged by the API; this one was not
        # expected, and the guest is told it is safe to try again.
        logger.warning(
            "Confirm of proposal_id=%s returned unexpected HTTP %s.",
            proposal_id,
            response.status_code,
        )
    status = _CONFIRM_STATUS_BY_HTTP_CODE.get(response.status_code, "unreachable")
    detail = _response_detail(response)
    if status in ("unavailable", "unreachable"):
        return ConfirmOutcome(
            status=status,
            message=detail or (
                "The booking system is temporarily unavailable. Your "
                "request is still pending — try Confirm again."
            ),
            keep_pending=True,
        )
    return ConfirmOutcome(
        status=status,
        message=detail or "Could not confirm this request.",
        keep_pending=False,
    )


def _dismiss_proposal(proposal_id: str, customer_id: int) -> None:
    """Dismiss a pending proposal, best-effort.

    A failure to reach the API is logged and otherwise ignored: the
    proposal's own server-side TTL is the backstop, and the caller has
    already dropped it from local state either way. An error status is not
    logged, since a 404 for a proposal the server already invalidated on the
    guest's next message is the normal case.

    Args:
        proposal_id: Proposal to dismiss.
        customer_id: Guest dismissing it.

    """
    try:
        httpx2.post(
            f"{_API_BASE}/v1/booking/dismiss",
            json={"proposal_id": proposal_id, "customer_id": customer_id},
            timeout=_HEALTH_TIMEOUT_S,
        )
    except Exception as exc:  # noqa: BLE001
        _log_api_failure(exc, "Could not dismiss proposal_id=%s.", proposal_id)


def _dismiss_pending_proposal() -> None:
    """Dismiss and clear any proposal left pending in session state."""
    proposal = st.session_state.get("pending_proposal")
    if proposal is None:
        return
    customer_id = st.session_state.get("customer_id")
    if customer_id is not None:
        _dismiss_proposal(proposal["proposal_id"], customer_id)
    st.session_state.pending_proposal = None


# ============================
# Guest claim registry
# ============================
#
# The whole HuggingFace Space runs as one Streamlit process (see
# deploy/supervisord.conf), and every browser session lives inside it as a
# thread of that same process, so a plain module-level dict guarded by a
# lock is enough to keep concurrent sessions off each other's guest --
# no database table or backend endpoint required. It resets if the process
# restarts, which is fine: that clears every session's UI state too.


@dataclasses.dataclass
class _GuestClaim:
    """One guest's exclusive claim by a live session.

    Attributes:
        session_id: Opaque id of the Streamlit session holding the guest.
        last_seen: UTC timestamp of the claim holder's most recent activity.

    """

    session_id: str
    last_seen: datetime


_guest_claims: dict[int, _GuestClaim] = {}
_guest_claims_lock = threading.Lock()


def _try_claim_guest(session_id: str, candidate_ids: list[int]) -> int | None:
    """Claim a random unclaimed guest for a session that has none yet.

    Sweeps out any claims that have gone stale before computing availability,
    so a guest whose previous session vanished without a clean release comes
    back into rotation instead of staying reserved forever.

    Args:
        session_id: Session id to record as the new claim's holder.
        candidate_ids: All seeded guest ids to choose among.

    Returns:
        int | None: The claimed guest's id, or ``None`` if every guest is
        currently claimed by a live session.

    """
    with _guest_claims_lock:
        _sweep_expired_claims_locked()
        available = [cid for cid in candidate_ids if cid not in _guest_claims]
        if not available:
            return None
        chosen = secrets.choice(available)
        _guest_claims[chosen] = _GuestClaim(
            session_id=session_id,
            last_seen=datetime.now(UTC),
        )
        return chosen


def _sweep_expired_claims_locked() -> None:
    """Drop claims idle past `_GUEST_CLAIM_TTL_S`.

    Callers must hold `_guest_claims_lock`.

    """
    cutoff = datetime.now(UTC) - timedelta(seconds=_GUEST_CLAIM_TTL_S)
    expired = [cid for cid, claim in _guest_claims.items() if claim.last_seen < cutoff]
    for cid in expired:
        del _guest_claims[cid]


def _touch_claim(customer_id: int, session_id: str) -> int | None:
    """Refresh a held claim's activity timestamp, or release it if it's lost.

    Recreates the claim if it is missing -- e.g. after a process restart
    cleared the registry, or after a hard refresh restored `customer_id`
    from the URL -- so a session that still holds this guest does not lose
    it on the next claim attempt. If another session's claim has taken over
    this guest in the meantime (its TTL lapsed and it was reassigned before
    this session got back to it), the guest is no longer ours to touch:
    this returns `None` instead of stealing it back.

    Args:
        customer_id: Guest whose claim to refresh.
        session_id: Id of the session asking to hold the claim.

    Returns:
        int | None: `customer_id` if the claim is (still) held by
        `session_id`, `None` if another session now holds it.

    """
    with _guest_claims_lock:
        claim = _guest_claims.get(customer_id)
        if claim is not None and claim.session_id != session_id:
            return None
        _guest_claims[customer_id] = _GuestClaim(
            session_id=session_id,
            last_seen=datetime.now(UTC),
        )
        return customer_id


def _release_claim(customer_id: int | None) -> None:
    """Release a held claim immediately, e.g. on an intentional sign-out.

    Args:
        customer_id: Guest to release, or ``None`` to no-op (nothing to do
            for a session that never claimed a guest).

    """
    if customer_id is None:
        return
    with _guest_claims_lock:
        _guest_claims.pop(customer_id, None)


def _persist_guest_identity(customer_id: int) -> None:
    """Write the session and guest ids into the URL query params.

    Lets the next `_init_session_state()` call -- after a hard refresh --
    restore the same guest claim instead of claiming a fresh one, since
    `st.session_state` does not survive a refresh but the URL does.

    Args:
        customer_id: Guest id currently held by this session.

    """
    st.query_params["sid"] = st.session_state.session_id
    st.query_params["cid"] = str(customer_id)


