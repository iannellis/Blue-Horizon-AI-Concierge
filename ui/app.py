def _int_or_none(value: str | None) -> int | None:
    """Parse a query-param string as an int, tolerating anything malformed.

    Args:
        value: Raw query-param value, or ``None`` if the param was absent.

    Returns:
        int | None: The parsed integer, or ``None`` if ``value`` is ``None``
        or not a valid integer.

    """
    if value is None:
        return None
    try:
        return int(value)
    except ValueError:
        return None


def _init_session_state() -> None:
    """Initialise all required ``st.session_state`` keys on first run.

    Restores ``session_id`` and ``customer_id`` from the ``sid``/``cid`` URL
    query params when present, so a hard refresh reconnects to the same
    guest claim instead of burning a fresh one -- ``st.session_state``
    itself does not survive a refresh, but the URL does. `_render_guest_
    assignment()` still verifies the restored claim actually belongs to
    this session before trusting it. A fresh conversation thread ID and
    empty message history are created regardless: a refresh is meant to
    reset the conversation, just not the guest.
    """
    if "session_id" not in st.session_state:
        # Unlike thread_id, never regenerated by _reset_session(), since a
        # "New Conversation" click resets the chat thread, not who is
        # holding the guest claim.
        st.session_state.session_id = st.query_params.get("sid") or str(
            uuid.uuid4(),
        )
    if "thread_id" not in st.session_state:
        st.session_state.thread_id = str(uuid.uuid4())
    if "customer_id" not in st.session_state:
        st.session_state.customer_id = _int_or_none(st.query_params.get("cid"))
    if "messages" not in st.session_state:
        st.session_state.messages = []
    if "pending_proposal" not in st.session_state:
        st.session_state.pending_proposal = None
    if "pending_resend" not in st.session_state:
        # The guest's own text from a chat turn that failed to complete, so
        # "Send again" can replay it verbatim instead of asking them to
        # retype -- see ChatTurnResult and _render_pending_resend.
        st.session_state.pending_resend = None
    if "pending_resend_message" not in st.session_state:
        st.session_state.pending_resend_message = None
    if "api_online" not in st.session_state:
        # Refreshed by _render_sidebar() every rerun, before _render_chat()
        # reads it. The optimistic default only matters for the one render
        # that happens before _render_sidebar() has run once.
        st.session_state.api_online = True


def _reset_session() -> None:
    """Clear the conversation and start a new thread.

    Generates a fresh ``thread_id``, empties the message history, and
    dismisses any pending proposal -- a dialog from a conversation that no
    longer exists must not still be confirmable. Also drops any pending
    resend, since it holds text addressed to the conversation just ending.
    """
    _dismiss_pending_proposal()
    st.session_state.thread_id = str(uuid.uuid4())
    st.session_state.messages = []
    st.session_state.pending_resend = None
    st.session_state.pending_resend_message = None


